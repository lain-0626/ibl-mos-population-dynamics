"""
make_figure3.py

Assemble existing cross-subject result figures into Figure 3.

No analysis is recomputed here.
All panels were generated by the analysis notebook.
"""

from pathlib import Path

import matplotlib.pyplot as plt


# ============================================================
# 1. Paths
# ============================================================

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent


RESULTS_DIR = Path(
    r"D:\Ephys_analysis\ibl-population-dynamics"
    r"\results\cross_session_MOs\summary_figures"
)


OUTPUT_DIR = (
    PROJECT_DIR
    / "figures"
    / "figure3"
)

OUTPUT_DIR.mkdir(
    parents=True,
    exist_ok=True,
)


# ============================================================
# 2. Existing notebook-generated figures
# ============================================================

PANEL_A_PATH = (
    RESULTS_DIR
    / "03_cross_subject_excursion_timecourse.png"
)

PANEL_B_PATH = (
    RESULTS_DIR
    / "01_cross_subject_excursion_vs_contrast.png"
)

PANEL_C_PATH = (
    RESULTS_DIR
    / "04_cross_subject_separation_timecourse.png"
)

PANEL_D_PATH = (
    RESULTS_DIR
    / "02_cross_subject_separation_vs_contrast.png"
)


# ============================================================
# 3. Check files
# ============================================================

panel_paths = [
    PANEL_A_PATH,
    PANEL_B_PATH,
    PANEL_C_PATH,
    PANEL_D_PATH,
]


for path in panel_paths:

    if not path.exists():

        raise FileNotFoundError(
            f"Cannot find:\n{path}"
        )

    print(
        path.name,
        "-> OK"
    )


# ============================================================
# 4. Read images
# ============================================================

panel_images = [
    plt.imread(path)
    for path in panel_paths
]


# ============================================================
# 5. Assemble Figure 3
# ============================================================

fig, axes = plt.subplots(
    nrows=2,
    ncols=2,
    figsize=(10, 8),
)


panel_labels = [
    "A",
    "B",
    "C",
    "D",
]


for ax, image, label in zip(
    axes.flat,
    panel_images,
    panel_labels,
):

    ax.imshow(
        image
    )

    ax.axis(
        "off"
    )

    ax.text(
        -0.03,
        1.03,
        label,
        transform=ax.transAxes,
        fontsize=16,
        fontweight="bold",
        ha="left",
        va="top",
    )


fig.subplots_adjust(
    left=0.02,
    right=0.98,
    bottom=0.02,
    top=0.98,
    wspace=0.05,
    hspace=0.08,
)


# ============================================================
# 6. Save
# ============================================================

png_path = (
    OUTPUT_DIR
    / "Figure3_cross_subject_magnitude.png"
)

pdf_path = (
    OUTPUT_DIR
    / "Figure3_cross_subject_magnitude.pdf"
)

svg_path = (
    OUTPUT_DIR
    / "Figure3_cross_subject_magnitude.svg"
)


fig.savefig(
    png_path,
    dpi=300,
    bbox_inches="tight",
    facecolor="white",
)

fig.savefig(
    pdf_path,
    bbox_inches="tight",
    facecolor="white",
)

fig.savefig(
    svg_path,
    bbox_inches="tight",
    facecolor="white",
)


print("\nSaved:")
print(png_path)
print(pdf_path)
print(svg_path)


plt.show()